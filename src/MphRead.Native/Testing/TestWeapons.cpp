template <std::size_t N>
[[nodiscard]] std::vector<RawWeaponInfo> parse_table(
    const std::array<std::uint8_t, N>& bytes) {
    static_assert(N % sizeof(RawWeaponInfo) == 0);
    const std::span<const std::uint8_t> input(bytes.data(), bytes.size());
    std::vector<RawWeaponInfo> result;
    result.reserve(N / sizeof(RawWeaponInfo));
    for (std::size_t offset = 0; offset < N; offset += sizeof(RawWeaponInfo)) {
        result.push_back(read::read_struct<RawWeaponInfo>(input, offset));
    }
    return result;
}

[[nodiscard]] std::string beam_member(formats::BeamType value) {
    switch (value) {
    case formats::BeamType::PowerBeam: return "PowerBeam";
    case formats::BeamType::VoltDriver: return "VoltDriver";
    case formats::BeamType::Missile: return "Missile";
    case formats::BeamType::Battlehammer: return "Battlehammer";
    case formats::BeamType::Imperialist: return "Imperialist";
    case formats::BeamType::Judicator: return "Judicator";
    case formats::BeamType::Magmaul: return "Magmaul";
    case formats::BeamType::ShockCoil: return "ShockCoil";
    case formats::BeamType::OmegaCannon: return "OmegaCannon";
    case formats::BeamType::Platform: return "Platform";
    case formats::BeamType::Enemy: return "Enemy";
    default: return "None";
    }
}

[[nodiscard]] std::string weapon_flags_string(WeaponFlags value) {
    constexpr std::array<std::pair<WeaponFlags, std::string_view>, 23> names{{
        {WeaponFlags::PartialCharge, "PartialCharge"},
        {WeaponFlags::CanCharge, "CanCharge"},
        {WeaponFlags::RepeatFire, "RepeatFire"},
        {WeaponFlags::CanZoom, "CanZoom"},
        {WeaponFlags::RicochetUncharged, "RicochetUncharged"},
        {WeaponFlags::RicochetCharged, "RicochetCharged"},
        {WeaponFlags::AutoRelease, "AutoRelease"},
        {WeaponFlags::SelfDamageUncharged, "SelfDamageUncharged"},
        {WeaponFlags::SelfDamageCharged, "SelfDamageCharged"},
        {WeaponFlags::ForceEffectUncharged, "ForceEffectUncharged"},
        {WeaponFlags::ForceEffectCharged, "ForceEffectCharged"},
        {WeaponFlags::AoeUncharged, "AoeUncharged"},
        {WeaponFlags::AoeCharged, "AoeCharged"},
        {WeaponFlags::Continuous, "Continuous"},
        {WeaponFlags::DestroyableUncharged, "DestroyableUncharged"},
        {WeaponFlags::DestroyableCharged, "DestroyableCharged"},
        {WeaponFlags::RadIdx1Uncharged, "RadIdx1Uncharged"},
        {WeaponFlags::RadIdx2Uncharged, "RadIdx2Uncharged"},
        {WeaponFlags::RadIdx1Charged, "RadIdx1Charged"},
        {WeaponFlags::RadIdx2Charged, "RadIdx2Charged"},
        {WeaponFlags::LifeDrainUncharged, "LifeDrainUncharged"},
        {WeaponFlags::LifeDrainCharged, "LifeDrainCharged"},
        {WeaponFlags::SurfaceCollision, "SurfaceCollision"}
    }};
    const auto raw = static_cast<std::uint32_t>(value);
    if (raw == 0) {
        return "WeaponFlags.None";
    }
    std::string result;
    for (const auto& [flag, name] : names) {
        if ((raw & static_cast<std::uint32_t>(flag)) != 0) {
            if (!result.empty()) {
                result += " | ";
            }
            result += "WeaponFlags.";
            result += name;
        }
    }
    return result;
}

[[nodiscard]] std::string affliction_string(formats::Affliction value) {
    const auto raw = static_cast<std::uint8_t>(value);
    if (raw == 0) {
        return "Affliction.None";
    }
    std::string result;
    constexpr std::array<std::pair<std::uint8_t, std::string_view>, 3> names{{
        {1, "Freeze"}, {2, "Disrupt"}, {4, "Burn"}
    }};
    for (const auto& [flag, name] : names) {
        if ((raw & flag) != 0) {
            if (!result.empty()) {
                result += " | ";
            }
            result += "Affliction.";
            result += name;
        }
    }
    return result;
}

void write_text_line(std::ostream& output, std::string_view label,
                     std::string_view value, bool last) {
    output << "                " << label << ": " << value
           << (last ? "\n" : ",\n");
}

template <typename T>
void write_number_line(std::ostream& output, std::string_view label,
                       T value, bool last) {
    output << "                " << label << ": "
           << static_cast<std::int64_t>(value)
           << (last ? "\n" : ",\n");
}

template <typename T>
void write_u8_array_line(std::ostream& output, std::string_view label,
                        const std::array<T, 2>& values, bool last) {
    output << "                " << label << ": new byte[] { "
           << static_cast<unsigned int>(values[0]) << ", "
           << static_cast<unsigned int>(values[1]) << " }"
           << (last ? "\n" : ",\n");
}

void write_u16_array_line(std::ostream& output, std::string_view label,
                          const std::array<std::uint16_t, 2>& values,
                          bool last) {
    output << "                " << label << ": new ushort[] { "
           << values[0] << ", " << values[1] << " }"
           << (last ? "\n" : ",\n");
}

void write_affliction_array_line(
    std::ostream& output, std::string_view label,
    const std::array<formats::Affliction, 2>& values, bool last) {
    output << "                " << label << ": new Affliction[] { "
           << affliction_string(values[0]) << ", "
           << affliction_string(values[1]) << " }"
           << (last ? "\n" : ",\n");
}

void write_hex_u32_array_line(
    std::ostream& output, std::string_view label,
    const std::array<std::uint32_t, 2>& values, bool last) {
    output << "                " << label << ": new uint[] { 0x"
           << std::uppercase << std::hex << values[0] << ", 0x"
           << values[1] << std::nouppercase << std::dec << " }"
           << (last ? "\n" : ",\n");
}

