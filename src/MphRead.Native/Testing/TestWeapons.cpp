    TestWeapons::RawWeaponInfo& TestWeapons::RawWeaponInfo::operator=(
        const RawWeaponInfo& other) noexcept
    {
        if (std::addressof(*this) != std::addressof(other))
        {
            this->~RawWeaponInfo();
            ::new (static_cast<void*>(this)) RawWeaponInfo(other);
        }
        return *this;
    }

