    template <typename T>
    T TestWeapons::RawWeaponInfo::ReadScalar(
        std::span<const std::uint8_t, 0xF0> raw, std::size_t offset) noexcept
    {
        T value{};
        std::memcpy(static_cast<void*>(std::addressof(value)),
            raw.data() + offset, sizeof(T));
        return value;
    }

    template <typename T>
    std::shared_ptr<ManagedArray<T>> TestWeapons::RawWeaponInfo::ReadArray2(
        std::span<const std::uint8_t, 0xF0> raw, std::size_t offset)
    {
        auto values = std::make_shared<ManagedArray<T>>(2);
        (*values)[0] = ReadScalar<T>(raw, offset);
        (*values)[1] = ReadScalar<T>(raw, offset + sizeof(T));
        return values;
    }

