void test_weapon_info(std::ostream& output) {
    const auto weapons_1p = get_1p_weapons();
    const auto weapons_mp = get_mp_weapons();
    const auto enemies = get_enemy_weapons();
    const auto platforms = get_platform_weapons();
    const auto ricochets = get_ricochets();

    const auto print_auto_release = [&output](const auto& table) {
        for (const RawWeaponInfo& weapon : table) {
            if ((static_cast<std::uint32_t>(weapon.flags())
                 & static_cast<std::uint32_t>(WeaponFlags::AutoRelease)) != 0) {
                output << beam_member(weapon.beam) << " ("
                       << beam_member(weapon.beam_kind) << ")\n";
                output << weapon_flags_string(weapon.flags()) << "\n\n";
            }
        }
    };
    print_auto_release(weapons_1p);
    print_auto_release(weapons_mp);
    print_auto_release(enemies);
    print_auto_release(platforms);
    print_auto_release(ricochets);

    for (std::size_t index = 0; index < 9; ++index) {
        const RawWeaponInfo& single_normal = weapons_1p[index];
        const RawWeaponInfo& multi_normal = weapons_mp[index];
        const RawWeaponInfo& single_affinity = weapons_1p[index + 9];
        const RawWeaponInfo& multi_affinity = weapons_mp[index + 9];
        output << beam_member(single_normal.beam) << "\n";
        output << "1P Nrm: " << single_normal.uncharged_spread << " / "
               << single_normal.min_charge_spread << " / "
               << single_normal.charged_spread << "\n";
        output << "MP Nrm: " << multi_normal.uncharged_spread << " / "
               << multi_normal.min_charge_spread << " / "
               << multi_normal.charged_spread << "\n";
        output << "1P Aff: " << single_affinity.uncharged_spread << " / "
               << single_affinity.min_charge_spread << " / "
               << single_affinity.charged_spread << "\n";
        output << "MP Aff: " << multi_affinity.uncharged_spread << " / "
               << multi_affinity.min_charge_spread << " / "
               << multi_affinity.charged_spread << "\n\n";
    }
}

