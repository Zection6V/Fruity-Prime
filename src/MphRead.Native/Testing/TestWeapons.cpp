    void TestWeapons::TestWeaponInfo()
    {
        const Weapons::WeaponList& weapons1P = *Weapons::Weapons1P;
        const Weapons::WeaponList& weaponsMP = *Weapons::WeaponsMP;
        const Weapons::WeaponList& enemies = *Weapons::EnemyWeapons;
        const Weapons::WeaponList& bosses = *Weapons::BossWeapons;
        const Weapons::WeaponList& platforms = *Weapons::PlatformWeapons;
        const Weapons::WeaponList& ricochets = *Weapons::Ricochets;

        const std::array<const Weapons::WeaponList*, 6> lists{
            &weapons1P, &weaponsMP, &enemies, &bosses, &platforms, &ricochets
        };
        for (const Weapons::WeaponList* list : lists)
        {
            for (const std::shared_ptr<WeaponInfo>& weapon : *list)
            {
                const WeaponInfo& weap = *weapon;
                if ((static_cast<std::uint32_t>(weap.Flags)
                    & static_cast<std::uint32_t>(WeaponFlags::AutoRelease)) != 0)
                {
                    WriteLine(BeamTypeToString(weap.Beam) + " (" + BeamTypeToString(weap.BeamKind) + ")");
                    WriteLine(WeaponFlagsToString(weap.Flags));
                    WriteLine();
                }
            }
        }

        Nop();

        for (std::int32_t i = 0; i < 9; ++i)
        {
            const WeaponInfo& singleNormal = *weapons1P.at(static_cast<std::size_t>(i));
            const WeaponInfo& multiNormal = *weaponsMP.at(static_cast<std::size_t>(i));
            const WeaponInfo& singleAffinity = *weapons1P.at(static_cast<std::size_t>(i + 9));
            const WeaponInfo& multiAffinity = *weaponsMP.at(static_cast<std::size_t>(i + 9));

            WriteLine(singleNormal.Name());
            WriteLine("1P Nrm: " + FormatInt32(singleNormal.UnchargedSpread)
                + " / " + FormatInt32(singleNormal.MinChargeSpread)
                + " / " + FormatInt32(singleNormal.ChargedSpread));
            WriteLine("MP Nrm: " + FormatInt32(multiNormal.UnchargedSpread)
                + " / " + FormatInt32(multiNormal.MinChargeSpread)
                + " / " + FormatInt32(multiNormal.ChargedSpread));
            WriteLine("1P Aff: " + FormatInt32(singleAffinity.UnchargedSpread)
                + " / " + FormatInt32(singleAffinity.MinChargeSpread)
                + " / " + FormatInt32(singleAffinity.ChargedSpread));
            WriteLine("MP Aff: " + FormatInt32(multiAffinity.UnchargedSpread)
                + " / " + FormatInt32(multiAffinity.MinChargeSpread)
                + " / " + FormatInt32(multiAffinity.ChargedSpread));
            WriteLine();
        }

        Nop();
    }

